"""Cross-check every bundled system against pymatgen and write docs/validation/pymatgen-crosscheck.md.

Run from the repository root with pymatgen installed:

    python scripts/pymatgen_crosscheck.py
"""

from __future__ import annotations

import csv
import sys
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import pourbase as pb  # noqa: E402
from pourbase.crosscheck import crosscheck  # noqa: E402

OUTPUT = ROOT / "docs" / "validation"
ACTIVITIES = (-6.0, -2.0)
DUPLICATE_TOLERANCE_J_MOL = 100.0


def water_equivalent_pairs(database: pb.ThermodynamicDatabase) -> list[tuple]:
    """Species of one system that differ only by whole water molecules, with their hydration energy."""
    water = database.reference_state.water_gibbs_energy_J_mol
    pairs = []
    for symbol, _name in database.available_systems():
        species = [item for item in database.load_system(symbol).species if item.is_ligand_free]
        for index, a in enumerate(species):
            for b in species[index + 1:]:
                if (a.phase != b.phase or a.charge != b.charge or a.metal_count != b.metal_count
                        or a.protons_per_metal != b.protons_per_metal or a.core_oxygen_count == b.core_oxygen_count):
                    continue
                waters = a.core_oxygen_count - b.core_oxygen_count
                energy = a.gibbs_energy_J_mol - b.gibbs_energy_J_mol - waters * water
                pairs.append((symbol, a, b, waters, energy))
    return pairs


def main() -> None:
    warnings.filterwarnings("ignore")
    database = pb.open_database()
    water = database.reference_state.water_gibbs_energy_J_mol
    results = []
    for symbol, _name in database.available_systems():
        for log10_activity in ACTIVITIES:
            scenario = pb.Scenario(symbol, concentration=log10_activity, allow_incomplete=True)
            diagram = pb.calculate(scenario, database).diagram
            results.append((log10_activity, crosscheck(diagram, water, aligned=True),
                            crosscheck(diagram, water, aligned=False)))
    pairs = water_equivalent_pairs(database)
    duplicates = [item for item in pairs if abs(item[4]) <= DUPLICATE_TOLERANCE_J_MOL]

    OUTPUT.mkdir(parents=True, exist_ok=True)
    with (OUTPUT / "pymatgen-crosscheck.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["symbol", "log10_activity", "species_compared", "aligned_agreement",
                         "aligned_max_energy_difference_eV", "shipped_agreement",
                         "shipped_disagreement_beyond_ties", "shipped_max_energy_difference_eV"])
        for log10_activity, aligned, shipped in results:
            writer.writerow([aligned.symbol, log10_activity, aligned.species_compared,
                             f"{aligned.agreement:.6f}", f"{aligned.max_energy_difference_eV:.3e}",
                             f"{shipped.agreement:.6f}", f"{shipped.disagreement_beyond_ties:.6f}",
                             f"{shipped.max_energy_difference_eV:.3e}"])

    aligned_exact = sum(item[1].agreement == 1.0 for item in results)
    worst_aligned = max(item[1].max_energy_difference_eV for item in results)
    shipped = sorted(results, key=lambda item: item[2].disagreement_beyond_ties, reverse=True)
    lines = [
        "# Cross-check against pymatgen",
        "",
        f"Generated by `scripts/pymatgen_crosscheck.py` with pourbase {pb.__version__} and the bundled "
        f"dataset. Every system is calculated at fixed activity (log₁₀ a = "
        f"{', '.join(f'{value:g}' for value in ACTIVITIES)}) on the default grid, and its species, "
        "energies and activities are evaluated again with pymatgen's `PourbaixEntry`. Ligand complexes "
        "are not compared.",
        "",
        "## Aligned constants",
        "",
        "pymatgen takes ΔfG°(H₂O) = −237.190 kJ/mol and a Nernst slope of 0.0591 V; pourbase takes "
        f"{water / 1000:.3f} kJ/mol from the database and the exact slope RT ln 10 / F. With pymatgen "
        "set to the same two constants:",
        "",
        f"- {aligned_exact} of {len(results)} diagrams have the same stable species at every grid point;",
        f"- the largest energy difference of any species at any point is {worst_aligned * 1000:.2e} meV.",
        "",
        "## pymatgen's own constants",
        "",
        "| System | log₁₀ a | Same species | Differing beyond ties | Main differing pair |",
        "|---|---|---|---|---|",
    ]
    for log10_activity, _aligned, result in shipped[:12]:
        pair = result.differing_pairs[0] if result.differing_pairs else None
        text = f"`{pair[0]}` / `{pair[1]}`" if pair else ""
        lines.append(f"| {result.symbol} | {log10_activity:g} | {result.agreement:.2%} | "
                     f"{result.disagreement_beyond_ties:.2%} | {text} |")
    lines += [
        "",
        "The rounded slope moves boundaries between hydroxide complexes by a few millivolts. The large "
        "differences come from species recorded twice under formulas that differ only by water, listed "
        "below: their energies agree within the rounding of the source, so the water constant decides "
        "which of the two is drawn.",
        "",
        "## Species recorded under two water-equivalent formulas",
        "",
        f"Pairs in one system whose energies differ by at most {DUPLICATE_TOLERANCE_J_MOL:g} J/mol once "
        "the water molecules are accounted for.",
        "",
        "| System | Species | Equivalent species | Water difference | ΔG (J/mol) |",
        "|---|---|---|---|---|",
    ]
    for symbol, a, b, waters, energy in sorted(duplicates, key=lambda item: abs(item[4])):
        lines.append(f"| {symbol} | {a.species} (`{a.record_id}`) | {b.species} (`{b.record_id}`) | "
                     f"{waters:+g} H₂O | {energy:+.0f} |")
    (OUTPUT / "pymatgen-crosscheck.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{aligned_exact}/{len(results)} aligned diagrams identical; {len(duplicates)} duplicate pairs; "
          f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
